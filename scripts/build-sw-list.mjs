// Generates sw-list.js, the list of files the service worker precaches, plus the version that names its cache.
// The shell is index.html, every stylesheet, every script and the brand icons. Tests, the catalog and the changelog
// are fetched network-first at run time. Run it after bumping js/version.js (npm run stamp:version does both).
//   node scripts/build-sw-list.mjs
import { readdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { SITE_VERSION } from '../js/version.js';

const ROOT = fileURLToPath(new URL('../', import.meta.url));
const OUT = `${ROOT}sw-list.js`;

async function walk(dir, ext, out = []) {
  for (const e of await readdir(`${ROOT}${dir}`, { withFileTypes: true })) {
    if (e.isDirectory()) await walk(`${dir}${e.name}/`, ext, out);
    else if (e.name.endsWith(ext)) out.push(`${dir}${e.name}`);
  }
  return out;
}

/** Paths relative to the site root, sorted so the output is stable. */
export async function precacheFiles() {
  const icons = (await readdir(`${ROOT}assets/brand`)).filter((f) => f.endsWith('.png')).map((f) => `assets/brand/${f}`);
  const files = ['index.html', 'manifest.webmanifest', ...(await walk('css/', '.css')), ...(await walk('js/', '.js')), ...icons];
  return files.sort();
}

export async function buildSwList(version = SITE_VERSION) {
  const files = await precacheFiles();
  return `// Generated by scripts/build-sw-list.mjs; do not edit. Loaded by sw.js.\nself.CW_SW = ${JSON.stringify({ version, files }, null, 2)};\n`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  await writeFile(OUT, await buildSwList());
  console.log(`wrote sw-list.js for ${SITE_VERSION}`);
}
